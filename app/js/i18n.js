let lang = 'en';
try { const s = localStorage.getItem('lang'); if (s === 'en' || s === 'tr') lang = s; } catch { /* storage unavailable */ }
const listeners = [];

export function t(key, params) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll('{' + k + '}', v);
  return s;
}
export const getLang = () => lang;
export function setLang(l) {
  lang = l === 'tr' ? 'tr' : 'en';
  try { localStorage.setItem('lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = lang;
  applyDom(); listeners.forEach(f => f(lang));
}
export const onLangChange = f => listeners.push(f);
export function applyDom(root = document) { // data-i18n, data-i18n-title, data-i18n-aria
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
export function extend(en, tr) { Object.assign(DICT.en, en); Object.assign(DICT.tr, tr); } // later modules add their own strings
